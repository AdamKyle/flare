/**
 * `PillTabs` wrapper horizontal alignment. `CENTER` preserves the existing
 * default appearance; `START` left-aligns the tab list so it reads as
 * directly connected to controls above it (e.g. Plane/Import/Export) rather
 * than floating in the middle of a full-width workspace.
 */
export enum PillTabsAlignment {
  CENTER = 'center',
  START = 'start',
}
